-- 003: every model call ("run") and the thumbs up/down on it.

-- Why log every call? It's how we answer "what did this cost?", "how often
-- does the model return broken JSON?", "are we hitting free-tier limits?"
-- and "was this answer from the real model or the mock?". Without a row per
-- call, those questions are guesses.
--
-- What is NOT logged here: secrets (a blocked_secret run stores no input
-- at all, see the CHECK below) and nothing ever goes to server logs except
-- ids, counts and status (lib/log.ts). The raw pasted code is kept ONLY in
-- input_text, which only its owner can read (repos filter by user_id;
-- admins see aggregates, never input_text or output).
CREATE TABLE runs (
  id                       uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  -- ON DELETE CASCADE: runs are personal data; deleting a user (or a demo
  -- user after 24h) must delete their code too.
  user_id                  uuid NOT NULL REFERENCES users (id) ON DELETE CASCADE,
  mode                     text NOT NULL CHECK (mode IN ('explain', 'generate', 'review', 'fix', 'tests', 'convert')),
  -- Source language (for generate: the language to write in).
  language                 text NOT NULL CHECK (language IN ('javascript', 'typescript', 'python', 'php', 'java', 'csharp', 'go', 'sql', 'html_css')),
  -- Convert only: the target language. The CHECK ties it to the mode, so a
  -- "convert" without a target (or a "review" with one) can't exist.
  target_language          text CHECK (target_language IN ('javascript', 'typescript', 'python', 'php', 'java', 'csharp', 'go', 'sql', 'html_css')),
  -- Explain only: beginner / intermediate / expert.
  level                    text CHECK (level IN ('beginner', 'intermediate', 'expert')),
  -- Tests only: the framework asked for (e.g. "vitest", "pytest").
  framework                text CHECK (char_length(framework) <= 40),
  -- SHA-256 of the input, not the input: lets analytics spot repeated
  -- submissions without the code itself.
  input_hash               char(64) NOT NULL CHECK (input_hash ~ '^[0-9a-f]{64}$'),
  input_chars              integer NOT NULL CHECK (input_chars >= 0),
  -- The owner's own copy of what they pasted, so /history can show it.
  input_text               text,
  -- The optional error message / stack trace (fix) or description (generate).
  input_extra              text,
  -- Structured answers are jsonb (validated by Zod before saving); text and
  -- unstructured fallbacks are stored as {"text": "..."}.
  output                   jsonb,
  output_kind              text CHECK (output_kind IN ('structured', 'text')),
  -- 'pending' is written BEFORE the model call (see lib/services/runs.ts);
  -- 'interrupted' is a stream the browser disconnected from part-way.
  status                   text NOT NULL DEFAULT 'pending' CHECK (status IN (
                             'pending', 'ok', 'invalid_output', 'refused', 'error', 'timeout',
                             'rate_limited', 'fallback_mock', 'blocked_secret', 'interrupted')),
  -- Short machine code for errors ('timeout', 'http_500'); never a message
  -- that could echo user input.
  error_code               text CHECK (char_length(error_code) <= 40),
  provider                 text NOT NULL CHECK (provider IN ('gemini', 'mock', 'none')),
  model                    text NOT NULL CHECK (char_length(model) <= 80),
  -- Which prompt template produced this answer (lib/ai/prompts.ts).
  prompt_version           text NOT NULL CHECK (char_length(prompt_version) <= 20),
  -- Token counts as reported by the provider (estimated by the mock).
  input_tokens             integer NOT NULL DEFAULT 0 CHECK (input_tokens >= 0),
  output_tokens            integer NOT NULL DEFAULT 0 CHECK (output_tokens >= 0),
  latency_ms               integer CHECK (latency_ms >= 0),
  -- What this call WOULD cost on a paid plan, in integer micro-dollars
  -- (1 USD = 1,000,000). Integers: no 0.1 + 0.2 float drift in sums.
  estimated_cost_micro_usd bigint NOT NULL DEFAULT 0 CHECK (estimated_cost_micro_usd >= 0),
  -- Generated by the browser once per submission (idempotency key).
  client_request_id        uuid NOT NULL,
  created_at               timestamptz NOT NULL DEFAULT now(),
  updated_at               timestamptz NOT NULL DEFAULT now(),
  completed_at             timestamptz,

  -- Idempotency: a double tap or a network retry sends the same id; the
  -- second INSERT hits this constraint and we return the first run instead
  -- of calling the model twice. Per user, so ids can't collide across users.
  CONSTRAINT runs_user_request_key UNIQUE (user_id, client_request_id),
  -- Target for composite foreign keys (feedback, snippets.source_run_id):
  -- lets a child row say "this run AND this owner", so the database itself
  -- refuses a child pointing at someone else's run.
  CONSTRAINT runs_id_user_key UNIQUE (id, user_id),
  CONSTRAINT runs_target_only_for_convert CHECK ((mode = 'convert') = (target_language IS NOT NULL)),
  CONSTRAINT runs_level_only_for_explain CHECK (mode = 'explain' OR level IS NULL),
  CONSTRAINT runs_framework_only_for_tests CHECK (mode = 'tests' OR framework IS NULL),
  -- A run blocked by the secrets scanner never stores what was pasted: the
  -- detected secret is in there. Enforced by the database, not just code.
  CONSTRAINT runs_blocked_secret_stores_no_input CHECK (
    status <> 'blocked_secret' OR (input_text IS NULL AND input_extra IS NULL)),
  -- output and output_kind come and go together.
  CONSTRAINT runs_output_kind_with_output CHECK ((output IS NULL) = (output_kind IS NULL))
);

-- /history: "my runs, newest first", paged by keyset (created_at, id).
-- The id tie-breaker makes the order total even when two runs share a
-- timestamp, so no row is skipped or shown twice between pages.
CREATE INDEX runs_user_created_idx ON runs (user_id, created_at DESC, id DESC);
-- /admin analytics: "all runs in the last 7 / 30 days".
CREATE INDEX runs_created_idx ON runs (created_at);

CREATE TABLE feedback (
  id         uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  run_id     uuid NOT NULL,
  user_id    uuid NOT NULL,
  rating     text NOT NULL CHECK (rating IN ('up', 'down')),
  -- Optional, short, only meaningful for thumbs-down (feeds /admin).
  reason     text CHECK (char_length(reason) <= 300),
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  -- Composite FK: the pair (run_id, user_id) must exist in runs, i.e. you
  -- can only rate your OWN run. ON DELETE CASCADE: feedback on a deleted
  -- run is meaningless. (This also covers user deletion, via runs.)
  CONSTRAINT feedback_run_owner_fk FOREIGN KEY (run_id, user_id)
    REFERENCES runs (id, user_id) ON DELETE CASCADE,
  -- One rating per person per run; changing your mind is an upsert.
  CONSTRAINT feedback_run_user_key UNIQUE (run_id, user_id),
  CONSTRAINT feedback_reason_only_down CHECK (rating = 'down' OR reason IS NULL)
);

-- /admin: recent thumbs-down reasons.
CREATE INDEX feedback_created_idx ON feedback (created_at DESC);
